#!/usr/bin/env python3
"""Write the files that help AI agents find their way around kitesink.com.

1. public/.well-known/agent-skills/index.json: the Agent Skills discovery index (RFC v0.2.0,
   https://github.com/cloudflare/agent-skills-discovery-rfc). One entry per
   public/.well-known/agent-skills/<name>/SKILL.md, with the SHA-256 of that file's bytes.
   Edit a SKILL.md, run this, and the digest follows.
2. The generated block of public/_headers: a Link header (RFC 8288) on every page that has a
   plain-text twin, pointing at the twin, and on the home page at /llms.txt as well. The
   twins come from TWINS in scripts/check_site.py.
3. worker/asset-headers.js: the rules of public/_headers as data. Cloudflare does not apply
   _headers to responses from a Worker, so worker/ai-twins.js applies these itself.

    python3 scripts/build_agent_files.py            # write all three
    python3 scripts/build_agent_files.py --check    # exit 1 if any is out of date
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
SKILLS = PUBLIC / ".well-known" / "agent-skills"
HEADERS = PUBLIC / "_headers"
WORKER_HEADERS = ROOT / "worker" / "asset-headers.js"
SCHEMA = "https://schemas.agentskills.io/discovery/0.2.0/schema.json"
BEGIN = "# BEGIN generated by scripts/build_agent_files.py: Link headers for agent discovery. Do not edit by hand."
END = "# END generated Link headers"

sys.path.insert(0, str(ROOT / "scripts"))
from check_site import TWINS  # noqa: E402  (the one list of pages and their twins)


def frontmatter(text: str, label: str) -> dict[str, str]:
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        raise SystemExit(f"{label}: no YAML frontmatter")
    fields = {}
    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        if value:
            fields[key.strip()] = value.strip()
    return fields


def skills_index() -> str:
    skills = []
    for path in sorted(SKILLS.glob("*/SKILL.md")):
        label = path.relative_to(ROOT).as_posix()
        raw = path.read_bytes()
        meta = frontmatter(raw.decode("utf-8"), label)
        name, description = meta.get("name", ""), meta.get("description", "")
        if name != path.parent.name:
            raise SystemExit(f"{label}: name {name!r} must equal its folder name")
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name) or len(name) > 64:
            raise SystemExit(f"{label}: name {name!r} must be 1-64 lowercase letters, digits and single hyphens")
        if not description or len(description) > 1024:
            raise SystemExit(f"{label}: description must be 1-1024 characters")
        skills.append({
            "name": name,
            "type": "skill-md",
            "description": description,
            "url": f"/.well-known/agent-skills/{name}/SKILL.md",
            "digest": "sha256:" + hashlib.sha256(raw).hexdigest(),
        })
    if not skills:
        raise SystemExit(f"{SKILLS.relative_to(ROOT)}: no skills found")
    return json.dumps({"$schema": SCHEMA, "skills": skills}, indent=2, ensure_ascii=False) + "\n"


def link_block() -> str:
    lines = [BEGIN]
    for route, twin in TWINS.items():
        links = [f'</{twin}>; rel="alternate"; type="text/markdown"']
        if route == "/":
            links.append('</llms.txt>; rel="describedby"; type="text/plain"')
        lines += [route, "  Link: " + ", ".join(links), ""]
    lines[-1] = END
    return "\n".join(lines)


def headers_file() -> str:
    text = HEADERS.read_text(encoding="utf-8")
    block = link_block()
    if BEGIN in text:
        start, end = text.index(BEGIN), text.index(END) + len(END)
        return text[:start] + block + text[end:]
    return text.rstrip("\n") + "\n\n" + block + "\n"


def parse_headers(text: str) -> list[list]:
    """The rules of a _headers file, in order: [pattern, {name: value}]. Detach rules
    ("! Name") are not used on this site and are refused rather than half-supported."""
    rules: list[list] = []
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line[0].isspace():
            rules.append([line.strip(), {}])
            continue
        if not rules:
            raise SystemExit("public/_headers: a header line comes before any URL")
        name, sep, value = line.strip().partition(":")
        if not sep or name.startswith("!"):
            raise SystemExit(f"public/_headers: cannot read {line.strip()!r}")
        rules[-1][1][name.strip()] = value.strip()
    return rules


def worker_headers(headers_text: str) -> str:
    rules = json.dumps(parse_headers(headers_text), indent=1, ensure_ascii=False)
    return ("// GENERATED by scripts/build_agent_files.py from public/_headers. Do not edit by hand.\n"
            "// Cloudflare does not apply _headers to responses from a Worker, so worker/ai-twins.js\n"
            "// applies these rules itself to the pages it answers.\n"
            f"export const RULES = {rules};\n")


def outputs() -> dict[Path, str]:
    headers = headers_file()
    return {
        SKILLS / "index.json": skills_index(),
        HEADERS: headers,
        WORKER_HEADERS: worker_headers(headers),
    }


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("out of date, run python3 scripts/build_agent_files.py: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
